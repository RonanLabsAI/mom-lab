import sys, os, random; sys.path.insert(0, os.path.dirname(__file__))
from common import *
import pandas as pd
from huggingface_hub import hf_hub_download
SUF = "\n\nSolve the problem step by step. Put the final answer in \\boxed{}."
N = 150000
def main():
    R = "nvidia/OpenMathInstruct-2"; dfs = []
    for i in [0, 1]:
        p = hf_hub_download(R, f"data/train_1M-0000{i}-of-00003.parquet", repo_type="dataset")
        dfs.append(pd.read_parquet(p))
    df = pd.concat(dfs); print(len(df), df.columns.tolist())
    df = df[df.generated_solution.str.contains("boxed", regex=False) & ~df.generated_solution.str.contains("<llm-code>", regex=False)]
    print("after filter", len(df), df.problem_source.value_counts().to_dict())
    df = df.sample(n=min(N, len(df)), random_state=SEED)
    rows = [dict(id=f"openmath2-{i}", messages=[{"role":"user","content":p + SUF},{"role":"assistant","content":s}], domain="math", source="openmath2_"+ps)
            for i, (p, s, ps) in enumerate(zip(df.problem, df.generated_solution, df.problem_source))]
    finalize_train("math", rows, {"sources":{"openmath2":{"hf":R,"revision":hf_sha(R),"split":"train_1M shards 0-1, random sample","license":"CC BY 4.0 (outputs generated by Llama-3.1-405B-Instruct; Llama 3.1 community license terms apply to derived-model naming/attribution)"}},
        "filters":"kept solutions containing \\boxed and no <llm-code> python blocks"})
main()
