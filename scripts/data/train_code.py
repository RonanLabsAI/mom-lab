import sys, os; sys.path.insert(0, os.path.dirname(__file__))
from common import *
from datasets import load_dataset
def main():
    R = "ise-uiuc/Magicoder-OSS-Instruct-75K"
    d = load_dataset(R, split="train"); print(d.column_names)
    rows = [dict(id=f"magicoder-{i}", messages=[{"role":"user","content":r["problem"].strip()},{"role":"assistant","content":r["solution"].strip()}], domain="code", source="magicoder_oss_75k")
            for i, r in enumerate(d) if r["problem"] and r["solution"]]
    srcs = {"magicoder_oss_75k":{"hf":R,"revision":hf_sha(R),"license":"MIT (outputs generated by GPT-3.5-turbo: OpenAI terms apply)","n":len(rows)}}
    EXTRA = os.environ.get("CODE_EXTRA", "1") == "1"
    if EXTRA:
        R2 = "OpenCoder-LLM/opc-sft-stage2"
        for cfg in ["educational_instruct", "evol_instruct", "package_instruct"]:
            try:
                d2 = load_dataset(R2, cfg, split="train")
            except Exception as e:
                print("skip", cfg, str(e)[:100]); continue
            n0 = len(rows)
            for i, r in enumerate(d2):
                if r.get("instruction") and r.get("output"):
                    rows.append(dict(id=f"opc2-{cfg}-{i}", messages=[{"role":"user","content":r["instruction"].strip()},{"role":"assistant","content":r["output"].strip()}], domain="code", source=f"opc_sft_stage2_{cfg}"))
            srcs[f"opc_sft_stage2_{cfg}"] = {"hf":R2,"config":cfg,"revision":hf_sha(R2),"license":"MIT (card); some subsets generated with GPT-4/Qwen outputs","n":len(rows)-n0}
    finalize_train("code", rows, {"sources":srcs})
main()
